from __future__ import annotations

import sys
import tempfile
import unittest
from pathlib import Path
from zipfile import ZipFile

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
from package_existing_report import find_report_file, package_report


class PackageExistingReportTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        self.run = self.root / "reports" / "FPT_20261026_133154"
        (self.run / "sections").mkdir(parents=True)
        (self.run / "complete_report.md").write_text(
            "# FPT report\nA non-empty report generated by the sample fixture.\n",
            encoding="utf-8",
        )
        (self.run / "sections" / "market.md").write_text(
            "# Market analysis\nFixture SSI values.\n", encoding="utf-8"
        )
        (self.run / "complete_report.html").write_text(
            "<html><body>FPT fixture</body></html>", encoding="utf-8"
        )
        self.archive = self.root / "out.zip"

    def tearDown(self):
        self.temp.cleanup()

    def test_accepts_report_file_as_candidate(self):
        self.assertEqual(
            find_report_file(self.run / "complete_report.md"),
            (self.run / "complete_report.md").resolve(),
        )

    def test_accepts_run_directory_as_candidate(self):
        self.assertEqual(
            find_report_file(self.run),
            (self.run / "complete_report.md").resolve(),
        )

    def test_finds_latest_report_from_reports_root(self):
        self.assertEqual(
            find_report_file(None, roots=(self.root / "reports",)),
            (self.run / "complete_report.md").resolve(),
        )

    def test_zip_contains_nonempty_report_and_sibling_files(self):
        result = package_report(self.run / "complete_report.md", self.archive)
        self.assertEqual(result["file_count"], 3)
        self.assertGreater(result["archive_bytes"], 0)
        with ZipFile(self.archive) as zf:
            self.assertIsNone(zf.testzip())
            self.assertIn("FPT_20261026_133154/complete_report.md", zf.namelist())
            text = zf.read("FPT_20261026_133154/complete_report.md").decode("utf-8")
            self.assertIn("A non-empty report", text)

    def test_empty_report_is_rejected(self):
        empty = self.run / "empty.md"
        empty.write_text("", encoding="utf-8")
        with self.assertRaises(FileNotFoundError):
            package_report(empty, self.archive)

    def test_failed_build_does_not_overwrite_verified_archive(self):
        package_report(self.run / "complete_report.md", self.archive)
        before = self.archive.read_bytes()
        empty = self.run / "empty.md"
        empty.write_text("", encoding="utf-8")
        with self.assertRaises(FileNotFoundError):
            package_report(empty, self.archive)
        self.assertEqual(before, self.archive.read_bytes())


if ( __name__ == "__main__"):
    unittest.main(verbosity=2)
